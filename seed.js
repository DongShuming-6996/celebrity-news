async function seed() {
  const database = await initDb();

  // 检查是否已有模拟数据
  const existing = database.exec("SELECT COUNT(*) as count FROM reports WHERE type = 'simulated'");
  const count = existing[0].values[0][0];
  if (count > 0) {
    console.log(`已存在 ${count} 条模拟数据，跳过种子数据插入`);
    return;
  }

  const now = new Date();

  for (const report of simulatedReports) {
    const date = new Date(now);
    date.setDate(date.getDate() - report.daysAgo);
    date.setHours(8, 0, 0, 0);
    database.run(
      'INSERT INTO reports (celebrity, content, type, created_at) VALUES (?, ?, ?, ?)',
      ['周杰伦', report.content, 'simulated', date.toISOString()]
    );
  }

  saveDb();
  console.log(`已插入 ${simulatedReports.length} 条周杰伦模拟汇报数据`);
}

seed().catch(err => {
  console.error('种子数据插入失败:', err);
  process.exit(1);
});
